    file: "einvoice-error-codes-INV.json",
    out: "einvoice-inv.ts",
    exportName: "EINVOICE_INV_ERRORS",
    url: "https://einvoice1.gst.gov.in/others/geterrorcodes/INV",
    title: "e-invoice error codes, INV list (IRN generation, cancel, get)",
    header: FULL_HEADER,
