function node(n, path) {
  for (const k of Object.keys(n))
    if (!KNOWN.has(k)) throw new Error(`unhandled keyword ${k} at ${path}`);
  if (n.$ref !== undefined) {
    const code = REF[n.$ref];
    if (code === undefined) throw new Error(`unknown $ref ${n.$ref} at ${path}`);
    return code;
  }
  if (n.type === "array" && n.items === undefined && n.properties !== undefined) {
    // Source quirk (spec §13 C15): `type: "array"` with `properties` and no `items`. Read as an array of such objects.
    const obj = { ...n, type: "object" };
    delete obj.minItems;
    delete obj.maxItems;
    return { a: node(obj, `${path}[]`), q: 1, ...bounds(n) };
  }
  if (n.type === "array" || n.items !== undefined)
    return { a: node(n.items, `${path}[]`), ...bounds(n) };
  if (n.properties !== undefined) {
    if (n.additionalProperties !== false)
      throw new Error(`object without additionalProperties:false at ${path}`);
    const p = {};
    for (const [k, v] of Object.entries(n.properties)) p[k] = node(v, `${path}.${k}`);
    const out = n.required === undefined ? { p } : { r: n.required, p };
    if (n.anyOf !== undefined) {
      // Every anyOf in the source is a list of { required: [...] } alternatives (e.g. det or det_q).
      out.o = n.anyOf.map((alt) => {
        if (Object.keys(alt).length !== 1 || !Array.isArray(alt.required))
          throw new Error(`unhandled anyOf at ${path}`);
        return alt.required;
      });
    }
    return out;
  }
  if (n.type === "string") return "s";
  throw new Error(`unhandled node at ${path}`);
}

